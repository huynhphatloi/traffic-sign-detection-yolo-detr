"""Normalize the pkdarabi/cardetection Roboflow export into our Ultralytics layout.

The Kaggle dataset already ships as a Roboflow YOLO export: {train,valid,test}/images,
{train,valid,test}/labels, plus a data.yaml listing the 15 class names in id order. So
unlike a cross-domain pipeline there is NO id remapping here -- we keep the dataset's own
native 15 classes (configs/classes.yaml).

This script:
  1. discovers the train/valid/test splits under --raw (handles nested dirs via rglob),
  2. copies images + labels into data/processed/yolo/cardetection/{images,labels}/<split>,
     renaming Roboflow's `valid` -> `val` so Ultralytics finds it,
  3. verifies every label id is in [0, nc) and every label has a matching image,
  4. prints per-split image/box counts and the per-class box histogram (for the EDA),
  5. (optional) --write-configs regenerates configs/classes.yaml + configs/cardetection.yaml
     straight from the raw data.yaml so the class system can never drift from the labels.

Run: python -m src.data.prepare_dataset --raw data/raw/cardetection
"""
from __future__ import annotations

import argparse
import shutil
from collections import Counter
from pathlib import Path

import yaml

from .common import IMG_EXTS

# Roboflow names a split "valid"; Ultralytics expects "val".
SPLIT_ALIASES = {"train": "train", "valid": "val", "validation": "val", "val": "val", "test": "test"}


def load_source_names(raw: Path) -> list[str]:
    """Read the Roboflow data.yaml -> ordered list of class names (index == class id)."""
    yamls = [p for p in sorted(raw.rglob("*.yaml")) if p.name in ("data.yaml", "data.yml")]
    if not yamls:
        yamls = sorted(raw.rglob("*.yaml"))
    if not yamls:
        raise FileNotFoundError(
            f"No data.yaml found under {raw}. Expected a Roboflow YOLO export "
            "(download pkdarabi/cardetection from Kaggle)."
        )
    names = yaml.safe_load(yamls[0].read_text())["names"]
    if isinstance(names, dict):
        return [names[k] for k in sorted(names, key=int)]
    return list(names)


def _find_split_dirs(raw: Path) -> dict[str, Path]:
    """Map our split name -> the source split directory (the one containing images/)."""
    found: dict[str, Path] = {}
    for images_dir in raw.rglob("images"):
        if not images_dir.is_dir():
            continue
        src_split = images_dir.parent.name.lower()
        if src_split in SPLIT_ALIASES:
            found[SPLIT_ALIASES[src_split]] = images_dir.parent
    return found


def _iter_images(d: Path):
    for p in sorted(d.rglob("*")):
        if p.suffix.lower() in IMG_EXTS:
            yield p


def prepare(raw: Path, out: Path, nc: int) -> dict[str, Counter]:
    split_dirs = _find_split_dirs(raw)
    if not split_dirs:
        raise FileNotFoundError(f"No train/valid/test 'images' folders found under {raw}.")

    per_split_hist: dict[str, Counter] = {}
    for split, src_dir in sorted(split_dirs.items()):
        img_out = out / "images" / split
        lbl_out = out / "labels" / split
        img_out.mkdir(parents=True, exist_ok=True)
        lbl_out.mkdir(parents=True, exist_ok=True)

        hist: Counter = Counter()
        n_imgs = n_boxes = n_missing_lbl = 0
        for img in _iter_images(src_dir / "images"):
            shutil.copy2(img, img_out / img.name)
            n_imgs += 1
            src_lbl = src_dir / "labels" / f"{img.stem}.txt"
            lines = []
            if src_lbl.exists():
                for ln in src_lbl.read_text().splitlines():
                    parts = ln.split()
                    if len(parts) != 5:
                        continue
                    cid = int(parts[0])
                    if not 0 <= cid < nc:
                        raise ValueError(
                            f"Label id {cid} out of range [0,{nc}) in {src_lbl}. "
                            "classes.yaml does not match the dataset -- run --write-configs."
                        )
                    hist[cid] += 1
                    n_boxes += 1
                    lines.append(ln.strip())
            else:
                n_missing_lbl += 1
            (lbl_out / f"{img.stem}.txt").write_text("\n".join(lines))

        per_split_hist[split] = hist
        print(f"[prepare] {split}: images={n_imgs} boxes={n_boxes} "
              f"images_without_label={n_missing_lbl} -> {img_out}")
    return per_split_hist


def write_configs(raw: Path, configs_dir: Path) -> None:
    names = load_source_names(raw)
    nc = len(names)
    classes_yaml = "# Auto-generated by prepare_dataset.py --write-configs from the raw data.yaml.\n"
    classes_yaml += f"nc: {nc}\nnames:\n"
    classes_yaml += "".join(f"  {i}: {n}\n" for i, n in enumerate(names))
    (configs_dir / "classes.yaml").write_text(classes_yaml)

    data_yaml = "# Auto-generated by prepare_dataset.py --write-configs.\n"
    data_yaml += "path: ../data/processed/yolo/cardetection\n"
    data_yaml += "train: images/train\nval: images/val\ntest: images/test\n\n"
    data_yaml += f"nc: {nc}\nnames:\n"
    data_yaml += "".join(f"  - {n}\n" for n in names)
    (configs_dir / "cardetection.yaml").write_text(data_yaml)
    print(f"[prepare] wrote configs/classes.yaml + configs/cardetection.yaml ({nc} classes)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", type=Path, default=Path("data/raw/cardetection"))
    ap.add_argument("--out", type=Path, default=Path("data/processed/yolo/cardetection"))
    ap.add_argument("--write-configs", action="store_true",
                    help="regenerate configs/{classes,cardetection}.yaml from the raw data.yaml")
    args = ap.parse_args()

    from .common import CONFIGS_DIR

    if args.write_configs:
        write_configs(args.raw, CONFIGS_DIR)

    names = load_source_names(args.raw)
    hist = prepare(args.raw, args.out, nc=len(names))

    total = Counter()
    for c in hist.values():
        total.update(c)
    print("[prepare] per-class box totals:")
    for cid, name in enumerate(names):
        print(f"  {cid:>2} {name:<16} {total.get(cid, 0)}")


if __name__ == "__main__":
    main()
